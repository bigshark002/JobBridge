/** Shared HTTP helpers. */

export function isBlockedResponse(status, bodyText = "") {
  if (status === 403 || status === 429 || status === 503 || status === 999) return true;
  const t = String(bodyText || "").slice(0, 800).toLowerCase();
  return (
    t.includes("cf-browser-verification") ||
    t.includes("attention required") ||
    t.includes("access denied") ||
    t.includes("generated by cloudfront") ||
    t.includes("authwall")
  );
}

export function isRedirectResponse(res) {
  if (!res) return true;
  if (res.type === "opaqueredirect") return true;
  return res.status >= 300 && res.status < 400;
}

export function parseJson(text, fallback = null) {
  try {
    return JSON.parse(text);
  } catch {
    return fallback;
  }
}
